// اللغة المختارة: ?lang=xx ثم المحفوظة ثم لغة المتصفح ثم العربية
var LANG = (function(){
  var q = (location.search.match(/lang=(\w\w)/) || [])[1], s = null;
  try { s = localStorage.getItem('lang'); } catch(e) {}
  var b = (navigator.language || '').slice(0,2);
  return [q, s, b].filter(function(x){ return x && T[x]; })[0] || 'ar';
})();

function t(k) { return T[LANG][k] || T.en[k] || k; }

function setLang(l) {
  LANG = l;
  try { localStorage.setItem('lang', l); } catch(e) {}
  applyLang();
}

function applyLang() {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG == 'ar' ? 'rtl' : 'ltr';
  var els = document.querySelectorAll('[data-t]');
  for (var i = 0; i < els.length; i++) els[i].innerHTML = t(els[i].getAttribute('data-t'));
  var sel = document.getElementById('langsel');
  if (sel) sel.value = LANG;
  if (window.onLang) window.onLang();
}

function langSelect() {
  var h = '<select id="langsel" onchange="setLang(this.value)">';
  for (var k in LANGS) h += '<option value="' + k + '">' + LANGS[k] + '</option>';
  return h + '</select>';
}
